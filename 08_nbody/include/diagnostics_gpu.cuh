// diagnostics_gpu.cuh —— GPU 上计算诊断量（能量 / 动量 / 角动量 / max|a|）
#pragma once

#include <cuda_runtime.h>

#include "diagnostics.h"
#include "nbody_types.h"

namespace nbody {

// ---------------------------------------------------------------------------
// 为什么要把诊断量搬到 GPU
//
// 早期版本的诊断量全在主机侧算，代价是**两件事**：
//   1. 一次全状态 D2H（pos/vel/mass 共 7 个数组）；
//   2. 一次 O(N^2) 的势能求和，在 CPU 上跑。
//
// 第 2 项是真正的瓶颈。实测数据：N=65536 时 OpenMP 128 线程做一次
// O(N^2) 力评估要数秒，而 GPU 一步只要几毫秒。诊断量的计算量与力评估同阶，
// 所以**每调一次诊断 ≈ 白跑几百步模拟**。
// 后果是 --diag-interval 在大 N 下根本不能用：想看能量随时间的曲线，
// 就得付出比模拟本身高一两个数量级的代价。这让"能量误差在合理范围内"
// 这个硬性验收项在进阶规模上只能靠首尾两个点来主张。
//
// ---------------------------------------------------------------------------
// 精度：内层累加必须用 double，这一点不能妥协
// ---------------------------------------------------------------------------
// 力计算用 FP32 是对的（热点，且 FP32 误差在物理上无关紧要）。
// 但诊断量是**用来裁定"FP32 力计算够不够准"的尺子**，尺子本身必须更准。
// N=65536 时势能有约 2e9 次累加，若用 FP32：
//   相对误差 ~ 6e-8 * sqrt(2e9) ≈ 2.7e-3
// 而我们要测的能量守恒误差本身就在 1e-6~1e-7 量级 —— 尺子的噪声会比
// 被测量大四个数量级，结论完全失去意义。
// 所以这里**内层循环就用 double 累加**，与主机侧实现保持同一精度语义。
//
// 代价：sm_89 的 FP64 吞吐是 FP32 的 1/64，sm_61 是 1/32。
// 但诊断量是低频调用（每 diag_interval 步一次），且即便按 1/64 折算，
// GPU 仍远快于 CPU —— 这个权衡在 n_bodyversion.md 附录 E 里有实测数据。
//
// ---------------------------------------------------------------------------
// 与主机侧实现的关系：**不是替代，而是被它校验**
// ---------------------------------------------------------------------------
// 两者数学表达式相同但求和顺序不同（GPU 是分块 + 树形归约），
// 所以结果只应差在浮点重排级别。这给了一个免费的强门禁：
// 小 N 上两边都算一遍、逐项比对，能立刻抓住归约写错、
// 自交互项漏跳过、原子累加竞争之类的 bug。
// 主机侧实现因此**保留**，作为参考实现而非退路。
// ---------------------------------------------------------------------------

// GPU 诊断量的工作缓冲。全局累加器放在设备端，避免每次调用都 malloc。
// 复用同一份缓冲：诊断是串行调用的，没有并发风险。
struct DiagnosticsGpuWorkspace {
  double *accum = nullptr;               // 见 kAccumSlots
  unsigned long long *max_acc = nullptr; // 见 KernelDiagnostics 的位序说明
  bool allocated = false;
};

void AllocateDiagnosticsGpu(DiagnosticsGpuWorkspace *ws);
void FreeDiagnosticsGpu(DiagnosticsGpuWorkspace *ws);

// ---------------------------------------------------------------------------
// 累加精度
//
// 各版本文档里反复主张"诊断量的累加必须用 double"，论证是：
//   N=65536 时势能有约 2e9 次累加，FP32 相对误差 6e-8 × sqrt(2e9) ≈ 2.7e-3，
//   而要测的能量守恒误差本身在 1e-6~1e-7 量级 —— 尺子噪声比被测量大四个数量级。
//
// **但它长期只是推导，从未实测。** 一个被反复引用却没验证过的论断，
// 无论多有道理都是纸面的。kFloat32 这一档就是为了把它变成实验：
// 同一状态、同一表达式，只把累加器换成 float，看误差是否真的落在预言的量级。
//
// 这也是唯一能回答"若当初图省事用了 FP32 会怎样"的方式 ——
// 而报告里"为什么诊断必须 double"这句话的分量，取决于有没有这个对照。
// ---------------------------------------------------------------------------
enum class DiagAccum {
  kFloat64 = 0, // 生产路径：内层累加用 double
  kFloat32,     // 仅用于精度对照实验，不要用它产出正式数据
};

const char *DiagAccumName(DiagAccum a);

// 在 GPU 上算全部诊断量。
//
// 注意 d 必须持有**当前**状态：本函数只读 pos/vel/mass，不依赖 acc_*
// （加速度在内部重新算一遍，与力计算 kernel 无关），
// 因此它对"主循环用了哪一档 kernel"完全不敏感 —— 这正是它能当尺子的原因。
Diagnostics ComputeDiagnosticsGpu(const DeviceBodies &d, real G, real softening,
                                  DiagnosticsGpuWorkspace *ws,
                                  int block_size = 128,
                                  DiagAccum accum = DiagAccum::kFloat64,
                                  cudaStream_t stream = 0);

} // namespace nbody
