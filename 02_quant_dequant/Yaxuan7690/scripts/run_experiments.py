#!/usr/bin/env python3
# =============================================================================
#  run_experiments.py -- 生成测试数据, 跑完整个配置矩阵, 汇总误差/性能指标
#
#  产出:
#    data/tensors/*.tensor          输入矩阵 (random / normal / outlier)
#    data/params/*.params           量化参数文件
#    data/out/*_lowp.bin           低精度权重文件
#    data/out/*_dequant.bin        反量化结果
#    data/out/*_log.txt            误差与性能日志
#    data/summary.csv              全部配置的指标汇总
#
#  用法:
#    python scripts/run_experiments.py [--exe build/lpq_quant.exe] [--quick]
# =============================================================================
import argparse
import csv
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

FORMATS = [
    # (name, format, elem_format, block_size)
    ("mxfp8-e4m3", "mxfp8", "e4m3", 32),
    ("mxfp8-e5m2", "mxfp8", "e5m2", 32),
    ("mxfp4", "mxfp4", "e2m1", 32),
    ("nvfp4", "nvfp4", None, 16),
]

# 4/6 自适应块缩放的对照组合: 张量 / block 大小 / 输出类型 / 舍入都一样, 只换"块
# 缩放因子怎么选"这条规则. 基线 static_6 就是上面矩阵里的 nvfp4 (即 AbsMax 直接
# 编码成 E4M3), 这里补上其余四条规则, 用来做逐规则对照.
#   配置名 -> (CSV 的 format 列, scale_rule)
SCALE_RULES = [
    ("nvfp4-46-static4", "static_4"),
    ("nvfp4-46-absmax", "abs_max"),
    ("nvfp4-46-mae", "mae"),
    ("nvfp4-46-mse", "mse"),
]
SCALE_MODES = ["tensor", "block"]
OUTPUT_TYPES = ["fp16", "bf16", "fp32"]
ROUNDINGS = ["nearest", "stochastic"]

# 误差对比用的三种分布 (题目要求: 随机 / 正态 / 含异常值)
DISTS = [("random", 512), ("normal", 512), ("outlier", 512)]
# 性能测试用的大矩阵
PERF_DIST, PERF_N = "normal", 2048


def run(cmd, **kw):
    print("  $", " ".join(cmd))
    return subprocess.run(cmd, check=True, **kw)


def gen_tensor(out_dir, name, rows, cols, dist, dtype, seed):
    path = os.path.join(out_dir, "%s.tensor" % name)
    if os.path.exists(path):
        return path
    run([sys.executable, os.path.join("tools", "gen_data.py"),
         "--out-dir", out_dir, "--name", name, "--rows", str(rows), "--cols", str(cols),
         "--dist", dist, "--dtype", dtype, "--seed", str(seed)], cwd=ROOT)
    return path


def write_params(path, fmt, elem, block_size, scale_mode, output_type, rounding, gpu,
                 scale_rule=None):
    lines = ['# quantization parameters (generated by scripts/run_experiments.py)',
             'format = "%s"' % fmt]
    if elem:
        lines.append('elem_format = "%s"' % elem)
    lines += ['block_size = %d' % block_size,
              'scale_mode = "%s"' % scale_mode,
              'output_type = "%s"' % output_type,
              'rounding = "%s"' % rounding]

    if scale_rule:
        lines.append('scale_rule = "%s"' % scale_rule)

    lines += [              'target_gpu = "%s"' % gpu]
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    return path


def parse_log(path):
    """把 [section] key = value 形式的日志解析成 dict."""
    out, sec = {}, ""
    with open(path, "rb") as fb:
        raw = fb.read()
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError:
        text = raw.decode("gbk", errors="replace")
    for line in text.splitlines():
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            if line.startswith("[") and line.endswith("]"):
                sec = line[1:-1]
                continue
            if "=" in line:
                k, v = line.split("=", 1)
                out[(sec + "." + k.strip()) if sec else k.strip()] = v.strip()
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--exe", default=os.path.join("build", "lpq_quant.exe"))
    ap.add_argument("--repeat", type=int, default=20)
    ap.add_argument("--warmup", type=int, default=5)
    ap.add_argument("--quick", action="store_true", help="只跑一小部分配置")
    args = ap.parse_args()

    tdir = os.path.join(ROOT, "data", "tensors")
    pdir = os.path.join(ROOT, "data", "params")
    odir = os.path.join(ROOT, "data", "out")
    for d in (tdir, pdir, odir):
        os.makedirs(d, exist_ok=True)

    gpu = "RTX 5060 Ti (sm_120, CUDA 12.9)"

    # ---------------- 1. 生成输入矩阵 ----------------
    print("== generating tensors ==")
    tensors = []
    for dist, n in DISTS:
        nm = "%s_%d" % (dist, n)
        gen_tensor(tdir, nm, n, n, dist, "fp32", 12345 + n)
        tensors.append((nm, dist, n, n, "fp32"))
    gen_tensor(tdir, "%s_%d" % (PERF_DIST, PERF_N), PERF_N, PERF_N, PERF_DIST, "fp32", 999)
    tensors.append(("%s_%d" % (PERF_DIST, PERF_N), PERF_DIST, PERF_N, PERF_N, "fp32"))
    gen_tensor(tdir, "normal_%d_fp16" % PERF_N, PERF_N, PERF_N, "normal", "fp16", 999)
    tensors.append(("normal_%d_fp16" % PERF_N, "normal", PERF_N, PERF_N, "fp16"))

    # ---------------- 2. 生成参数文件 ----------------
    print("== generating params ==")
    configs = []
    for fname, fmt, elem, bs in FORMATS:
        for sm in SCALE_MODES:
            for ot in OUTPUT_TYPES:
                for rd in ROUNDINGS:
                    cname = "%s_%s_%s_%s" % (fname, sm, ot, rd)
                    p = os.path.join(pdir, cname + ".params")
                    write_params(p, fmt, elem, bs, sm, ot, rd, gpu)
                    configs.append((cname, fname, p))
    # 4/6 对照: 固定 block / fp16 / nearest, 只换 scale_rule
    for fname, rule in SCALE_RULES:
        cname = "%s_block_fp16_nearest" % fname
        p = os.path.join(pdir, cname + ".params")
        write_params(p, "nvfp4", None, 16, "block", "fp16", "nearest", gpu, scale_rule=rule)
        configs.append((cname, fname, p))

    if args.quick:
        configs = configs[::7]

    # ---------------- 3. 跑配置矩阵 ----------------
    rows, nrun = [], 0
    total = len(tensors) * len(configs)
    for tname, dist, r_, c_, dtype in tensors:
        for cname, fname, pfile in configs:
            out_pref = "%s__%s" % (tname, cname)
            log = os.path.join(odir, out_pref + "_log.txt")
            nrun += 1
            print("[%d/%d] %s x %s" % (nrun, total, tname, cname))
            # 用相对路径传参: Windows 下 argv 按 ANSI 代码页编码, 传入含中文的绝对路径
            # 会让 GBK 字节被写进日志, 破坏日志的 UTF-8 一致性.
            cmd = [os.path.abspath(os.path.join(ROOT, args.exe)),
                   "--input", "data/tensors/%s.tensor" % tname,
                   "--params", "data/params/%s.params" % cname,
                   "--out-dir", "data/out", "--out-prefix", out_pref,
                   "--repeat", str(args.repeat), "--warmup", str(args.warmup), "--quiet"]
            if r_ <= 512:
                cmd.append("--cpu-check")
            subprocess.run(cmd, check=True, cwd=ROOT)
            lg = parse_log(log)
            rows.append({
                "tensor": tname, "dist": dist, "rows": r_, "cols": c_,
                "in_dtype": dtype, "config": cname, "format": fname,
                "scale_mode": lg.get("config.scale_mode", ""),
                "block_size": lg.get("config.block_size", ""),
                "output_type": lg.get("config.output_type", ""),
                "rounding": lg.get("config.rounding", ""),
                "scale_rule": lg.get("config.scale_rule", ""),
                "numel": lg.get("input.numel", ""),
                "packed_bytes": lg.get("lowp.packed_bytes", ""),
                "scale_bytes": lg.get("lowp.scale_bytes", ""),
                "total_lowp_bytes": lg.get("lowp.total_lowp_bytes", ""),
                "compression_ratio": lg.get("lowp.compression_ratio", "").split()[0],
                "bits_per_element": lg.get("lowp.bits_per_element", ""),
                "global_scale": lg.get("lowp.global_scale", ""),
                "max_abs_error": lg.get("error.max_abs_error", ""),
                "mae": lg.get("error.mae", ""),
                "mse": lg.get("error.mse", ""),
                "rmse": lg.get("error.rmse", ""),
                "relative_mse": lg.get("error.relative_mse", ""),
                "amax_ms": lg.get("performance.amax_kernel_ms", ""),
                "scale_ms": lg.get("performance.scale_kernel_ms", ""),
                "quantize_ms": lg.get("performance.quantize_kernel_ms", ""),
                "quantize_total_ms": lg.get("performance.quantize_total_ms", ""),
                "dequantize_ms": lg.get("performance.dequantize_kernel_ms", ""),
                "input_passes": lg.get("performance.quantize_input_passes", ""),
                "bw_quant_GBps": lg.get("performance.effective_bandwidth_quantize_GBps", ""),
                "bw_dequant_GBps": lg.get("performance.effective_bandwidth_dequantize_GBps", ""),
                "cpu_quantize_ms": lg.get("accuracy_check_cpu_reference.cpu_quantize_ms", ""),
                "cpu_dequantize_ms": lg.get("accuracy_check_cpu_reference.cpu_dequantize_ms", ""),
                "speedup_quantize": lg.get(
                    "accuracy_check_cpu_reference.speedup_quantize_gpu_vs_cpu", ""),
                "speedup_dequantize": lg.get(
                    "accuracy_check_cpu_reference.speedup_dequantize_gpu_vs_cpu", ""),
            })

    csv_path = os.path.join(ROOT, "data", "summary.csv")
    cols = list(rows[0].keys())
    with open(csv_path, "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols)
        w.writeheader()
        w.writerows(rows)
    print("wrote %s (%d rows)" % (csv_path, len(rows)))


if __name__ == "__main__":
    main()